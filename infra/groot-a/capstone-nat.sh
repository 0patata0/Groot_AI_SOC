#!/bin/bash
# Groot_A NAT 게이트웨이 적용 스크립트 (Phase 1) + 관리용 포트포워딩. 멱등(idempotent).
# capstone-nat.service 가 docker.service 이후 실행한다. 수동 재적용도 안전.
set -e

EXT_IF="ens192"            # 임시 외부(인터넷) NIC. 향후 관리자 NAT 시 변경 가능
INT_IF="ens160"           # 내부망 NIC
INT_NET="10.10.10.0/24"   # 내부망 대역 (B=.10, C=.20, GW(A)=.1)
NFT_FILE="/etc/nftables.d/capstone-gw.nft"
FWD_FILE="/etc/nftables.d/capstone-fwd.nft"

# 관리 페이지 포트포워딩: "<A 외부포트>:<내부IP>:<내부포트>:<설명>"  (A의 $EXT_IF 로 들어온 TCP 를 내부로 DNAT)
#  - 정책(2026-09-27): **웹 VM 서비스(DVWA)만 기본 IP 로 외부 노출**(80). 관리포털(Wazuh 대시보드)은 특정 포트 10443 로 내리고 443 은 비운다.
#    → https://192.168.16.230/ (443) 는 응답 없음(관리포털이 기본 URL 에 안 뜸 = 하드닝). WAF TLS 는 8443 유지, 80 은 WAF(DVWA HTTP) 그대로.
#    VPN 경로는 A 로 22/80/443 만 통과(실측) → 10443 은 VPN 브라우저 도달 불가. VPN 에서는 대시보드 경로 없음(정책: VPN 비노출; 루프백 터널은 2026-09-28 제거).
#    (2026-09-28) 학과망(192.168.12.x)→VM세그먼트도 22/80/443 만 통과(10443 차단, 실측) → 대시보드는 A:443 chatproxy 의 wazuh.groot.lab
#    서버블록(출발지 allowlist: 학과망·VM세그먼트·내부망, VPN/외부 403)으로 서비스. 아래 10443 DNAT 는 VM세그먼트 직결(Kali/현장PC)용으로 유지.
#  - 회신은 A 를 거쳐 돌아와야 하므로 DNAT 된 연결은 $INT_IF 로 나갈 때 SNAT(masquerade) 한다
#    (B/C 기본라우트가 아직 ens192 라 비대칭 라우팅 방지; ens192 제거 후에도 그대로 유효). 내부 서버 로그엔 클라이언트가 10.10.10.1 로 보임.
#  - 공격 경로(DVWA)는 여기 넣지 않는다: WAF(80/8443)·IDS 를 거쳐야 한다.
PORTFORWARDS=(
  "10443:10.10.10.10:443:Wazuh dashboard (VM세그먼트 직결용: https://192.168.16.230:10443 ; 학과망/VM세그먼트는 https://wazuh.groot.lab (A:443 chatproxy) ; VPN: 없음(정책))"
)
# 참고: 채팅(Mattermost)은 A:443 nginx 리버스 프록시(chatproxy, https://chat.groot.lab)로 서비스 → 여기 DNAT 아님. (구 8065 DNAT 제거됨 2026-09-27)

# 1) IP forwarding (런타임). 영구화는 /etc/sysctl.d/99-capstone-nat.conf 가 담당.
sysctl -w net.ipv4.ip_forward=1 >/dev/null

# 2) 마스커레이드: 독립 nft 테이블(Docker 규칙과 공존). 멱등 위해 삭제 후 로드.
nft delete table ip capstone_gw 2>/dev/null || true
nft -f "$NFT_FILE"

# 3) forward 허용: Docker 의 FORWARD(policy DROP) 보다 먼저 점프되는 DOCKER-USER 에 ACCEPT.
if iptables -L DOCKER-USER -n >/dev/null 2>&1; then
  iptables -C DOCKER-USER -s "$INT_NET" -i "$INT_IF" -o "$EXT_IF" -j ACCEPT 2>/dev/null \
    || iptables -I DOCKER-USER -s "$INT_NET" -i "$INT_IF" -o "$EXT_IF" -j ACCEPT
  iptables -C DOCKER-USER -d "$INT_NET" -i "$EXT_IF" -o "$INT_IF" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null \
    || iptables -I DOCKER-USER -d "$INT_NET" -i "$EXT_IF" -o "$INT_IF" -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
else
  echo "WARN: DOCKER-USER 체인 없음 (docker 미기동?) — forward 허용 건너뜀" >&2
fi

# 4) 관리용 포트포워딩 (DNAT + 회신용 SNAT + FORWARD NEW 허용). 목록이 비면 테이블만 정리.
{
  echo "# generated by capstone-nat.sh — 관리 페이지 포트포워딩. 목록은 스크립트의 PORTFORWARDS."
  echo "table ip capstone_fwd {"
  echo "  chain prerouting {"
  echo "    type nat hook prerouting priority dstnat; policy accept;"
  for e in "${PORTFORWARDS[@]}"; do IFS=: read -r ep ip ipt desc <<<"$e"
    echo "    iifname \"$EXT_IF\" tcp dport $ep dnat to $ip:$ipt   # $desc"
  done
  echo "  }"
  echo "  chain postrouting {"
  echo "    type nat hook postrouting priority srcnat; policy accept;"
  echo "    oifname \"$INT_IF\" ct status dnat masquerade   # DNAT 된 연결의 회신이 A 로 돌아오게"
  echo "  }"
  echo "}"
} > "$FWD_FILE"
nft delete table ip capstone_fwd 2>/dev/null || true
nft -f "$FWD_FILE"
if iptables -L DOCKER-USER -n >/dev/null 2>&1; then
  for e in "${PORTFORWARDS[@]}"; do IFS=: read -r ep ip ipt desc <<<"$e"
    iptables -C DOCKER-USER -d "$ip" -i "$EXT_IF" -o "$INT_IF" -p tcp --dport "$ipt" -m conntrack --ctstate NEW -j ACCEPT 2>/dev/null \
      || iptables -I DOCKER-USER -d "$ip" -i "$EXT_IF" -o "$INT_IF" -p tcp --dport "$ipt" -m conntrack --ctstate NEW -j ACCEPT
  done
fi

# 5) Phase 2 호스트 방화벽 + agent_block. 한 트랜잭션으로 원자적 교체(실패 시 기존 테이블 유지, 무필터 창 없음).
#    차단 목록 복원: 재적용이면 커널 셋(남은 TTL), 부팅이면 /var/lib/capstone/agent_block.state(만료 제외). 결과는 syslog(agent_block reload)로.
#    FW_FILE 은 fw_phase2.sh 가 확인 전 임시경로(.pending)로 덮어쓸 수 있다. 부팅 시엔 확정 파일(capstone-fw.nft)만 본다.
FW_FILE=${FW_FILE:-/etc/nftables.d/capstone-fw.nft}
STATE=/var/lib/capstone/agent_block.state
if [ -f "$FW_FILE" ]; then
  nft -c -f "$FW_FILE"                       # 문법 오류면 여기서 중단(기존 테이블 유지)
  TMP=$(mktemp)
  { echo "table inet capstone_fw"; echo "delete table inet capstone_fw"; echo "include \"$FW_FILE\""; } > "$TMP"
  SRC=none
  if nft list set inet capstone_fw agent_block >/dev/null 2>&1; then
    if nft -j list set inet capstone_fw agent_block | python3 -c '
import json, sys
d = json.load(sys.stdin)
for o in d.get("nftables", []):
    for e in (o.get("set") or {}).get("elem", []):
        if isinstance(e, dict):
            r = int(float(e["elem"].get("expires", 0)))
            if r > 0: print("add element inet capstone_fw agent_block { %s timeout %ds }" % (e["elem"]["val"], r))
        else: print("add element inet capstone_fw agent_block { %s }" % e)' >> "$TMP"; then SRC=kernel
    else logger -t capstone-fw -p auth.warning "could not read current agent_block set; block list not carried over"; fi
  elif [ -s "$STATE" ]; then
    now=$(date +%s)
    while read -r bip bexp; do
      [ -n "$bip" ] && [ -n "$bexp" ] || continue; rem=$((bexp - now)); [ "$rem" -gt 0 ] || continue
      echo "add element inet capstone_fw agent_block { $bip timeout ${rem}s }" >> "$TMP"
    done < "$STATE"; SRC=statefile
  fi
  N=$(grep -c '^add element' "$TMP" || true)
  if ! nft -f "$TMP"; then rm -f "$TMP"; logger -t capstone-fw -p auth.err "capstone-fw.nft failed to load (previous table kept if any); host FW may be OFF"; exit 1; fi
  rm -f "$TMP"
  logger -t agent_block -p auth.notice -- "action=reload restored=$N source=$SRC result=ok by=capstone-nat" || true
  FW_STATE="on ($N blocked restored from $SRC)"
else
  FW_STATE="off (no $FW_FILE)"
fi

echo "capstone-nat 적용됨: masquerade $INT_NET -> $EXT_IF, DOCKER-USER forward 허용, 포트포워딩 ${#PORTFORWARDS[@]}건, host FW $FW_STATE"
for e in "${PORTFORWARDS[@]}"; do IFS=: read -r ep ip ipt desc <<<"$e"; echo "  $EXT_IF:$ep -> $ip:$ipt  ($desc)"; done
